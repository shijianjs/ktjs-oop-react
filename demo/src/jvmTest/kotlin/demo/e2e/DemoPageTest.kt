package demo.e2e

import com.microsoft.playwright.Page
import com.microsoft.playwright.assertions.PlaywrightAssertions.assertThat
import com.microsoft.playwright.options.AriaRole
import com.microsoft.playwright.junit.UsePlaywright
import com.microsoft.playwright.options.WaitUntilState
import kotlin.test.assertTrue
import org.junitpioneer.jupiter.RetryingTest

/**
 * The demo page, exercised the way a reader would: the object graph renders, an island re-renders on
 * its own, a route switches, a list grows, an error boundary holds, and the console stays quiet.
 *
 * These are the checks that make the annotation pipeline real — the metadata table is generated by
 * KSP at build time, the prototype patch happens at `initializeOopReact()`, and a mistake in either
 * shows up here as a page that never appears or a method returning a bare element.
 *
 * Every assertion goes through Playwright's retrying `assertThat`, because a state change arrives
 * after the click, not during it.
 */
@UsePlaywright(DemoOptions::class)
class DemoPageTest {

    @RetryingTest(maxAttempts = 2)
    fun `page renders the app shell`(page: Page) {
        openPage(page)

        assertTrue(page.title().contains("ktjs-oop-react"), "title: ${page.title()}")
        assertThat(page.getByText("ktjs-oop-react 演示")).isVisible()
        assertThat(page.getByText("计数器")).isVisible()
    }

    @RetryingTest(maxAttempts = 2)
    fun `clicking one island re-renders only that island`(page: Page) {
        openPage(page, "#/counter")

        assertThat(page.getByText("left: 0")).isVisible()
        assertThat(page.getByText("middle: 0")).isVisible()

        page.getByRole(AriaRole.BUTTON, Page.GetByRoleOptions().setName("+").setExact(true))
            .first()
            .click()

        assertThat(page.getByText("left: 1")).isVisible()
        assertThat(page.getByText("middle: 0")).isVisible()

        // The counter's own island ran again; the two siblings still show their first render.
        assertThat(page.getByText("rendered 2×", Page.GetByTextOptions().setExact(true))).hasCount(1)
        assertThat(page.getByText("rendered 1×", Page.GetByTextOptions().setExact(true))).hasCount(2)
    }

    @RetryingTest(maxAttempts = 2)
    fun `a list field grows and its summary follows`(page: Page) {
        openPage(page, "#/todos")

        assertThat(page.getByText("0 条未完成")).isVisible()

        page.locator("input").first().fill("写文档")
        page.getByRole(AriaRole.BUTTON, Page.GetByRoleOptions().setName("添加").setExact(true)).click()

        assertThat(page.getByText("写文档")).isVisible()
        assertThat(page.getByText("1 条未完成")).isVisible()

        page.locator("input[type=checkbox]").first().check()

        assertThat(page.getByText("0 条未完成")).isVisible()
    }

    @RetryingTest(maxAttempts = 2)
    fun `one island failing leaves the other one alive`(page: Page) {
        openPage(page, "#/failure")

        assertThat(page.getByText("这个岛一直在")).isVisible()
        assertThat(page.getByText("Render failed: FailurePage.broken")).isVisible()
    }

    @RetryingTest(maxAttempts = 2)
    fun `async rows load and selection is tracked`(page: Page) {
        openPage(page, "#/orders")

        assertThat(page.getByText("Acme 纸业")).isVisible()
        assertThat(page.getByText("已选 0 行")).isVisible()

        page.locator("input[type=checkbox]").first().check()

        assertThat(page.getByText("已选 1 行")).isVisible()
    }

    @RetryingTest(maxAttempts = 2)
    fun `switching the language re-renders the header and the nav`(page: Page) {
        openPage(page, "#/counter")

        page.getByRole(AriaRole.BUTTON, Page.GetByRoleOptions().setName("切换语言").setExact(true)).click()

        assertThat(page.getByRole(AriaRole.BUTTON, Page.GetByRoleOptions().setName("Counter").setExact(true)))
            .isVisible()
        assertThat(page.locator("html")).hasAttribute("lang", "en")

        page.getByRole(AriaRole.BUTTON, Page.GetByRoleOptions().setName("Toggle theme").setExact(true)).click()

        assertThat(page.locator("html")).hasAttribute("data-theme", "dark")
    }

    @RetryingTest(maxAttempts = 2)
    fun `page logs no unexpected console errors or failed requests`(page: Page) {
        val consoleErrors = mutableListOf<String>()
        val failedRequests = mutableListOf<String>()
        page.onConsoleMessage { message ->
            if (message.type() == "error") consoleErrors += message.text()
        }
        page.onRequestFailed { request ->
            failedRequests += "${request.url()} ${request.failure()}"
        }

        // Every page except `failure`, which throws on purpose and is covered by its own test.
        openPage(page, "#/counter")
        page.getByText("+", Page.GetByTextOptions().setExact(true)).first().click()
        page.getByRole(AriaRole.BUTTON, Page.GetByRoleOptions().setName("待办").setExact(true)).click()
        page.locator("input").first().fill("写文档")
        page.getByRole(AriaRole.BUTTON, Page.GetByRoleOptions().setName("添加").setExact(true)).click()
        page.getByRole(AriaRole.BUTTON, Page.GetByRoleOptions().setName("订单").setExact(true)).click()
        assertThat(page.getByText("Acme 纸业")).isVisible()
        page.getByRole(AriaRole.BUTTON, Page.GetByRoleOptions().setName("井字棋").setExact(true)).click()
        assertThat(page.getByText("轮到 X")).isVisible()

        assertTrue(consoleErrors.isEmpty(), "console errors: $consoleErrors")
        assertTrue(failedRequests.isEmpty(), "failed requests: $failedRequests")
    }

    private fun openPage(page: Page, hash: String = "") {
        page.navigate(
            "./$hash",
            Page.NavigateOptions().setWaitUntil(WaitUntilState.NETWORKIDLE),
        )
    }
}
